// A Fortran namelist file: groups '&record' ... '/', assignments 'name = value' separated by commas, blanks or new
// lines, '!' comments outside quotes. Repeat counts, arrays, several values for one name and text outside a group
// are errors, as is a group that is not closed.
std::map<std::string, NmlValue> read_namelist_file(const std::string& path) {
  std::ifstream in(path);
  if (!in) throw Error("cannot open namelist file " + path);
  std::stringstream all;
  all << in.rdbuf();
  const std::string s = all.str();
  std::map<std::string, NmlValue> kv;
  std::string record;  // empty: outside a group
  std::set<std::string> groups;  // the groups already read
  std::size_t i = 0;
  int line = 1;
  const auto where = [&] { return path + ":" + std::to_string(line); };
  const auto skip = [&](int* commas = nullptr) {  // blanks, commas (counted), new lines, comments
    while (i < s.size()) {
      const char c = s[i];
      if (c == '\n') {
        ++line;
        ++i;
      } else if (c == '!') {
        while (i < s.size() && s[i] != '\n') ++i;
      } else if (std::isspace(static_cast<unsigned char>(c)) || (c == ',' && !record.empty())) {
        if (c == ',' && commas) ++*commas;
        ++i;
      } else {
        break;
      }
    }
  };
  const auto word = [&] {  // a name
    const std::size_t a = i;
    while (i < s.size() && (std::isalnum(static_cast<unsigned char>(s[i])) || s[i] == '_')) ++i;
    return s.substr(a, i - a);
  };
  for (;;) {
    skip();
    if (i >= s.size()) break;
    const char c = s[i];
    if (record.empty()) {
      if (c != '&') throw Error(where() + ": text outside a namelist group");
      ++i;
      record = lower(word());
      if (record.empty() || record == "end") throw Error(where() + ": '&' without a namelist group name");
      if (!is_record(record)) throw Error(where() + ": &" + record + " is not a namelist record of MPAS-Atmosphere");
      // MPAS rewinds and reads each record once (gen_inc.c:855-857): only the first group of a name is read
      if (!groups.insert(record).second)
        throw Error(where() + ": group &" + record + " appears twice (MPAS reads only the first one; not handled)");
      continue;
    }
    if (c == '/') {
      ++i;
      record.clear();
      continue;
    }
    if (c == '&' || c == '$') throw Error(where() + ": group &" + record + " is not closed with '/'");
    const int name_line = line;
    const auto at = [&] { return path + ":" + std::to_string(name_line); };
    const std::string name = lower(word());
    if (name.empty()) throw Error(where() + ": unexpected '" + std::string(1, c) + "' in &" + record);
    // gfortran reads one ',' between the name and '=', and fails on a second ("Equal sign must follow namelist
    // object name": MPAS stops, gen_inc.c:910-911)
    int commas = 0;
    skip(&commas);
    if (commas > 1) throw Error(at() + ": more than one ',' between " + name + " and '='");
    if (i >= s.size() || s[i] != '=') throw Error(at() + ": " + name + " without '= value' (arrays are not handled)");
    ++i;
    if (!find_option(record, name))
      throw Error(at() + ": " + name + " is not an option of the namelist record &" + record + " of MPAS-Atmosphere");
    if (kv.count(name)) throw Error(at() + ": option " + name + " is set twice");
    // the value may be on a later line (gfortran reads it there); a comment before it is refused (gfortran's read then
    // ends with an end-of-file status and MPAS keeps the defaults of the rest of the record)
    while (i < s.size() && (s[i] == ' ' || s[i] == '\t' || s[i] == '\r' || s[i] == '\n')) {
      if (s[i] == '\n') ++line;
      ++i;
    }
    NmlValue v;
    v.record = record;
    if (i < s.size() && (s[i] == '\'' || s[i] == '"')) {
      const char q = s[i++];
      v.quoted = true;
      for (;;) {
        if (i >= s.size() || s[i] == '\n') throw Error(where() + ": unterminated character value of " + name);
        if (s[i] == q) {
          if (i + 1 < s.size() && s[i + 1] == q) {
            v.text += q;
            i += 2;
            continue;
          }
          ++i;
          break;
        }
        v.text += s[i++];
      }
    } else {
      const std::size_t a = i;
      while (i < s.size() && !std::isspace(static_cast<unsigned char>(s[i])) && s[i] != ',' && s[i] != '/' &&
             s[i] != '!')
        ++i;
      v.text = s.substr(a, i - a);
      if (v.text.empty()) throw Error(where() + ": " + name + " has no value");
      if (v.text.find('*') != std::string::npos) throw Error(where() + ": repeat counts are not handled (" + name + ")");
    }
    // a character value ends with a separator (blank, ',', '/', '!', end of line): gfortran fails on 'a'name = ...
    // ("Invalid string input": MPAS stops)
    if (v.quoted && i < s.size() && !std::isspace(static_cast<unsigned char>(s[i])) && s[i] != ',' && s[i] != '/' &&
        s[i] != '!')
      throw Error(where() + ": no separator after the character value of " + name);
    // the next item must be another name, the end of the group, or the end of a line / a separator
    std::size_t j = i;
    while (j < s.size() && (s[j] == ' ' || s[j] == '\t')) ++j;
    if (j < s.size() && s[j] != '\n' && s[j] != ',' && s[j] != '/' && s[j] != '!' && s[j] != '\r') {
      // another token on the same line: it must start "name =" (several assignments separated by blanks)
      std::size_t k = j;
      while (k < s.size() && (std::isalnum(static_cast<unsigned char>(s[k])) || s[k] == '_')) ++k;
      while (k < s.size() && (s[k] == ' ' || s[k] == '\t')) ++k;
      if (k == j || k >= s.size() || s[k] != '=')
        throw Error(where() + ": " + name + " has more than one value (arrays are not handled)");
    }
    kv[name] = v;
  }
  if (!record.empty()) throw Error(path + ": group &" + record + " is not closed with '/'");
  return kv;
}

std::map<std::string, std::string> effective_namelist(const std::string& path) {
  std::map<std::string, NmlValue> file;
  if (!path.empty()) file = read_namelist_file(path);
  std::map<std::string, std::string> out;
  const std::string src = path.empty() ? std::string("(no namelist file)") : path;
  for (const auto& o : kOptions) {
    const std::string key = lower(o.name);
    const auto it = file.find(key);
    std::string v = o.deflt;
    std::string shown = std::string(o.deflt) + " (Registry default)";
    if (it != file.end()) {
      v = normalise(o, it->second, src);
      shown = it->second.quoted ? "'" + it->second.text + "'" : it->second.text;
    }
    // the accepted value it matches is the normalised one (a real: the reference's spelling of the same double)
    bool ok = false;
    std::string match;
    const auto acc = accepted_values(o);
    for (const auto& a : acc)
      if (!ok && same_value(o, v, a)) {
        ok = true;
        match = a;
      }
    if (!ok) {
      std::string list;
      for (const auto& a : acc) list += (list.empty() ? "" : ", ") + a;
      throw Error(src + ": namelist option " + o.name + " = " + shown +
                  " has no verified port (verified against the MPAS references: " + list + ")");
    }
    out[key] = match;
  }
  return out;
}

InitConfig read_init_config(const std::string& path) {
  InitConfig c;
  const auto kv = effective_namelist(path);
  auto r = [&](const char* k, real& x) {
    const auto it = kv.find(k);
    if (it != kv.end()) x = c_strtod(it->second);
  };
  auto l = [&](const char* k, bool& x) {
    const auto it = kv.find(k);
    if (it != kv.end()) x = it->second == "true";
  };
  auto t = [&](const char* k, std::string& x) {
    const auto it = kv.find(k);
    if (it != kv.end()) x = it->second;
  };
  r("config_dt", c.config_dt);
  r("config_apvm_upwinding", c.config_apvm_upwinding);
  r("config_coef_3rd_order", c.config_coef_3rd_order);
  l("config_h_scalewithmesh", c.config_h_ScaleWithMesh);
  r("config_zd", c.config_zd);
  r("config_xnutr", c.config_xnutr);
  r("config_epssm_minimum", c.config_epssm_minimum);
  r("config_epssm_maximum", c.config_epssm_maximum);
  r("config_epssm_transition_bottom_z", c.config_epssm_transition_bottom_z);
  r("config_epssm_transition_top_z", c.config_epssm_transition_top_z);
  l("config_do_restart", c.config_do_restart);
  l("config_do_dacycling", c.config_do_DAcycling);
  r("config_len_disp", c.config_len_disp);
  t("config_start_time", c.config_start_time);
  r("config_epssm", c.config_epssm);
  l("config_positive_definite", c.config_positive_definite);
  l("config_apply_lbcs", c.config_apply_lbcs);
  t("config_les_model", c.config_les_model);
  t("config_physics_suite", c.config_physics_suite);
  t("config_microp_scheme", c.config_microp_scheme);
  t("config_convection_scheme", c.config_convection_scheme);
  t("config_pbl_scheme", c.config_pbl_scheme);
  return c;
}

std::vector<std::string> active_scalars(const InitConfig& c) {
  if (c.config_physics_suite != "none")
    throw Error("active scalars: config_physics_suite = '" + c.config_physics_suite + "' is not handled");
  if (c.config_les_model != "none") throw Error("active scalars: config_les_model = '" + c.config_les_model + "' is not handled");
  // mpas_atmphys_control.F:157-159: with the suite 'none', 'suite' means 'off'
  const auto off = [](const std::string& s) { return s == "suite" || s == "off"; };
  if (!off(c.config_convection_scheme) || !off(c.config_pbl_scheme))
    throw Error("active scalars: convection / PBL schemes are not handled");
  if (off(c.config_microp_scheme)) return {"qv"};
  if (c.config_microp_scheme == "mp_kessler") return {"qv", "qc", "qr"};
  throw Error("active scalars: config_microp_scheme = '" + c.config_microp_scheme + "' is not handled");
}

