"""Generate src/core/namelist_table.inc: every namelist option of MPAS-Atmosphere's Registry.xml (record, name, type,
Registry default) and the values CPPMPAS accepts for it: the value each verified reference configuration runs with
(the option's value in that reference's namelist.atmosphere, or the Registry default when the namelist leaves it
out). A configuration verified against a reference's output without being one of its runs (the MW restart run,
tests/namelists/MW_restart) is given as its own namelist. A value outside that set has no verified port and is a
hard error (CONSTITUTION.md 2.4).

The Registry is preprocessed as the atmosphere core's build does (DO_PHYSICS defined, MPAS_CAM_DYCORE and
MPAS_USE_MUSICA undefined, core_atmosphere/Makefile:9-11), with tools/gen_registry_table.py's preprocessor.

Values are written normalised: reals as Python's shortest round-trip repr of the double gfortran reads
(correctly rounded, d/D exponents as e), integers in decimal, logicals as true / false, characters unquoted.

usage: gen_namelist_table.py <Registry.xml> <namelist.atmosphere>... > src/core/namelist_table.inc
"""
import importlib.util
import math
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

_spec = importlib.util.spec_from_file_location("gen_registry_table", Path(__file__).with_name("gen_registry_table.py"))
_reg = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_reg)

REAL = re.compile(r"[+-]?(\d+\.?\d*|\.\d+)([eEdD][+-]?\d+)?")
INT = re.compile(r"[+-]?\d+")
LOGICAL = {"t": True, ".t.": True, "true": True, ".true.": True, "f": False, ".f.": False, "false": False,
           ".false.": False}


def normalise(typ, text, where):
    if typ == "real":
        if not REAL.fullmatch(text):
            sys.exit(f"{where}: '{text}' is not a real")
        x = float(re.sub("[dD]", "e", text))
        if not math.isfinite(x):
            sys.exit(f"{where}: '{text}' overflows a double")
        return repr(x)
    if typ == "integer":
        if not INT.fullmatch(text):
            sys.exit(f"{where}: '{text}' is not an integer")
        if not -2**31 <= int(text) <= 2**31 - 1:
            sys.exit(f"{where}: '{text}' is outside a 32-bit integer")
        return str(int(text))
    if typ == "logical":
        if text.lower() not in LOGICAL:
            sys.exit(f"{where}: '{text}' is not a logical")
        return "true" if LOGICAL[text.lower()] else "false"
    return text


def read_namelist(path):
    """{(record, option): (text, quoted)} of a namelist.atmosphere as MPAS's reference files write it: one
    'option = value' per line inside '&record' ... '/'."""
    out, rec = {}, None
    for n, line in enumerate(Path(path).read_text().splitlines(), 1):
        t = re.match(r"(?:[^!'\"]|'[^']*'|\"[^\"]*\")*", line).group(0).strip()  # up to a '!' outside quotes
        if not t:
            continue
        if t.startswith("&"):
            rec = t[1:].strip().lower()
            continue
        if t == "/":
            rec = None
            continue
        m = re.fullmatch(r"(\w+)\s*=\s*('([^']*)'|\"([^\"]*)\"|[^\s,]+)\s*,?", t)
        if rec is None or not m:
            sys.exit(f"{path}:{n}: not read: {line}")
        quoted = m.group(2)[0] in "'\""
        text = m.group(3) if m.group(3) is not None else m.group(4) if m.group(4) is not None else m.group(2)
        key = (rec, m.group(1).lower())
        if key in out:
            sys.exit(f"{path}:{n}: {key[1]} is set twice")
        out[key] = (text, quoted)
    return out


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    reg_path, namelists = sys.argv[1], sys.argv[2:]
    root = ET.fromstring(_reg.preprocess(reg_path))
    options = []
    for rec in root.iter("nml_record"):
        for o in rec.findall("nml_option"):
            default = o.get("default_value", "")
            if o.get("type") == "real":  # MPAS compiles a real default as printf("%lf", atof(...)) (gen_inc.c:810-811)
                default = "%f" % float(default)
            elif o.get("type") == "logical":  # only true / .true. compile to .true. (gen_inc.c:818-822)
                default = "true" if default in ("true", ".true.") else "false"
            options.append((rec.get("name"), o.get("name"), o.get("type"), default))
    refs = [read_namelist(p) for p in namelists]
    known = {(r.lower(), n.lower()) for r, n, _, _ in options}
    for p, ref in zip(namelists, refs):
        for key in ref:
            if key not in known:
                sys.exit(f"{p}: &{key[0]} {key[1]} is not an option of the Registry")
    print("// SPDX-License-Identifier: GPL-3.0-or-later")
    print("// GENERATED by tools/gen_namelist_table.py from MPAS-Atmosphere v8.4.2 src/core_atmosphere/Registry.xml")
    print("// (DO_PHYSICS defined) and the namelist.atmosphere files of the verified configurations:")
    for p in namelists:
        print("//   " + "/".join(Path(p).parts[-4:]))
    print("// Do not edit by hand. Columns: record, option, type, Registry default, accepted values (normalised, one")
    print("// per line: reals as the shortest round-trip decimal, logicals true / false).")
    for rec, name, typ, default in options:
        acc = []
        for p, ref in zip(namelists, refs):
            text, quoted = ref.get((rec.lower(), name.lower()), (default, typ == "character"))
            if typ == "character" and not quoted:
                sys.exit(f"{p}: {name} = {text}: a character value must be quoted")
            if typ != "character" and quoted:
                sys.exit(f"{p}: {name} = '{text}': a {typ} value must not be quoted")
            v = normalise(typ, text, f"{p}: {name}")
            if v not in acc:
                acc.append(v)
        d = normalise(typ, default, f"Registry {name}")
        print(f"CPPMPAS_NML_OPTION({cstr(rec)}, {cstr(name)}, {cstr(typ)}, {cstr(d)}, {cstr(chr(10).join(acc))})")


if __name__ == "__main__":
    main()
