"""Generate src/io/registry_atm_table.inc from MPAS-Atmosphere's core_atmosphere/Registry.xml.

The table holds, for every <var> and var_array constituent, what MPAS's registry generator turns into field
metadata (src/tools/registry/gen_inc.c): type, dimensions (Fortran order), default value, packages and the NetCDF
attributes MPAS writes (every XML attribute except those in ATTRS_TO_IGNORE, gen_inc.c:43-53, with 'description'
renamed 'long_name' and 'missing_value' renamed '_FillValue' (written as a number, gen_inc.c:39-41, 55-58),
in XML order. It also lists the variables of the atmosphere 'input' stream
(Registry.xml:602-648, with the nested 'invariant' stream, Registry.xml:499-600, expanded).

The registry is preprocessed as MPAS's build does for the atmosphere core: DO_PHYSICS defined
(core_atmosphere/Makefile:9-10), MPAS_CAM_DYCORE and MPAS_USE_MUSICA undefined.

usage: gen_registry_table.py <mpas_src>/src/core_atmosphere/Registry.xml > src/io/registry_atm_table.inc
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

DEFINED = {"DO_PHYSICS"}
IGNORED = {"name", "type", "dimensions", "persistence", "packages", "time_levs", "name_in_code", "array_group",
           "default_value"}
RENAMED = {"description": "long_name", "missing_value": "_FillValue"}


def preprocess(path):
    out, stack = [], []
    with open(path, encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            m = re.match(r"#\s*(ifdef|ifndef)\s+(\w+)", s)
            if m:
                cond = (m.group(2) in DEFINED) == (m.group(1) == "ifdef")
                stack.append(cond)
                continue
            if re.match(r"#\s*else", s):
                stack[-1] = not stack[-1]
                continue
            if re.match(r"#\s*endif", s):
                stack.pop()
                continue
            if not all(stack):
                continue
            m = re.match(r'#\s*include\s+"([^"]+)"', s)
            if m:
                inc = preprocess(os.path.join(os.path.dirname(path), m.group(1)))
                inc = re.sub(r"<\?xml[^>]*\?>", "", inc)
                out.append(inc)
                continue
            out.append(line)
    return "".join(out)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def default_of(el):
    """defaultValue as MPAS's registry generator sets it for a <var> or a <var_array> (whose constituents share it):
    the XML default_value, or, when there is none, the missing_value (gen_inc.c:1709-1715, 1286-1292)."""
    d = el.get("default_value")
    if d is not None:
        return d
    mv = el.get("missing_value")
    if mv is None:
        return ""
    if mv == "FILLVAL":  # MPAS_REAL_FILLVAL / MPAS_INT_FILLVAL (gen_inc.c:641-660): no value in this table yet
        sys.exit(f"{el.get('name')}: missing_value FILLVAL as default value is not handled")
    return mv


def attrs_of(el):
    parts = []
    for k, v in el.attrib.items():
        if k in IGNORED:
            continue
        parts.append(f"{RENAMED.get(k, k)}={v}")
    return "\n".join(parts)


def main():
    reg_path = sys.argv[1]
    root = ET.fromstring(preprocess(reg_path))
    rows = []
    for vs in root.iter("var_struct"):
        sname = vs.get("name")
        tl = vs.get("time_levs", "1")
        for child in vs:
            if child.tag == "var":
                rows.append((child.get("name"), sname, child.get("type"), child.get("dimensions", ""), "",
                             default_of(child), child.get("packages", ""), tl, attrs_of(child)))
            elif child.tag == "var_array":
                for c in child.findall("var"):
                    rows.append((c.get("name"), sname, child.get("type"), child.get("dimensions", ""),
                                 child.get("name"), default_of(child),
                                 c.get("packages", child.get("packages", "")), tl, attrs_of(c)))
    names = [r[0] for r in rows]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit(f"duplicate variable names: {sorted(dup)}")
    streams = {s.get("name"): s for s in root.iter("stream") if s.get("type")}

    def expand(sname):
        out = []
        for c in streams[sname]:
            if c.tag in ("var", "var_array"):
                out.append(c.get("name"))
            elif c.tag == "stream":
                out.extend(expand(c.get("name")))
        return out

    print("// SPDX-License-Identifier: GPL-3.0-or-later")
    print("// GENERATED by tools/gen_registry_table.py from MPAS-Atmosphere v8.4.2 src/core_atmosphere/Registry.xml")
    print("// (DO_PHYSICS defined, MPAS_CAM_DYCORE / MPAS_USE_MUSICA undefined). Do not edit by hand.")
    print("// Columns: name, var_struct, type, dimensions (Fortran order), var_array, default_value, packages, time_levs,")
    print("//          NetCDF attributes as written by MPAS ('key=value' lines, XML order).")
    print("#ifdef CPPMPAS_REGISTRY_VAR")
    for r in rows:
        print("CPPMPAS_REGISTRY_VAR(" + ", ".join([cstr(r[0]), cstr(r[1]), cstr(r[2]), cstr(r[3]), cstr(r[4]),
                                                 cstr(r[5]), cstr(r[6]), r[7], cstr(r[8])]) + ")")
    print("#endif")
    print("#ifdef CPPMPAS_INPUT_STREAM_VAR")
    for n in expand("input"):
        print(f"CPPMPAS_INPUT_STREAM_VAR({cstr(n)})")
    print("#endif")


if __name__ == "__main__":
    main()
